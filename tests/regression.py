"""Shared by the Phase 15 fixtures, the e2e test and the regression test (P15-4, P15-6).

**Why a synthetic model.** The shipped weights (`models/avtfd_g_seed0.pt`) are not in git --
`*.pt` is ignored and the file is 31 MB -- so CI cannot load them. The end-to-end and
regression tests instead run the real pipeline on a bundle whose every tensor is filled from
``numpy.random.default_rng(0)``. NumPy's PCG64 stream is specified and identical on every
platform and version, unlike ``torch.manual_seed`` initialisation, which is tied to the torch
build; so the "expected" outputs committed beside the fixtures are reproducible on a Linux CI
runner from a Windows-generated file. What this pins is the pipeline's *numerics* -- decode,
alignment, features, model forward, post-processing -- not detection quality: a random model
detects nothing. Detection quality has its own regression against the shipped model
(`test_shipped_model_regression`, local only).

**Why `.mkv` with PCM audio.** The plan names `tiny_*.mp4`; MP4 cannot hold PCM in ffmpeg,
and AAC decoders are allowed to differ in the last bits between ffmpeg builds. H.264 decoding
is bit-exact by specification and PCM is exact, so an `.mkv` (an accepted upload format)
removes the one source of cross-platform drift that is not the model's.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import numpy as np

FIXTURES = Path(__file__).resolve().parent / "fixtures"
TINY_REAL = FIXTURES / "tiny_real.mkv"
TINY_FAKE = FIXTURES / "tiny_fake.mkv"
EXPECTED = {
    TINY_REAL: FIXTURES / "expected_tiny_real.json",
    TINY_FAKE: FIXTURES / "expected_tiny_fake.json",
}
LABELS_SAMPLE = FIXTURES / "lavdf_labels_sample.json"

SECONDS = 2.0
FAKE_SPAN = (0.8, 1.2)  # where tiny_fake's picture and tone are swapped
SEED = 0
# Fixed post-processing for the regression: the plan's section 6.4 defaults, not the tuned
# dev values, so the fixture does not move if the shipped config is re-tuned.
REGRESSION_POSTPROCESS = {
    "threshold": 0.5,
    "median_kernel": 5,
    "closing": 3,
    "min_duration_s": 0.4,
    "merge_gap_s": 0.3,
    "merge_first": False,
    "refine_radius": 0,
    "fps": 25.0,
}


def seeded_bundle() -> dict:
    """A complete `VideoAnalyzer` bundle with platform-independent pseudo-random weights.

    Weights (>= 2-D) are N(0, 1/fan_in), the scale default initialisers use, so activations
    stay in range and the scores are not saturated; 1-D weights are 1 and biases 0 (the
    LayerNorm/BatchNorm identity); BatchNorm statistics are the identity too.
    """
    import torch

    from src.inference.pipeline import BUNDLE_FORMAT, model_kwargs_from_result
    from src.models.attention_model import AttentionFusionModel
    from src.models.backbones.visual import build_backbone

    rng = np.random.default_rng(SEED)

    def fill(state: dict) -> dict:
        out = {}
        for key in sorted(state):  # sorted: the draw order must not depend on dict order
            t = state[key]
            if not torch.is_floating_point(t):
                out[key] = t.clone()
            elif key.endswith("running_var") or (t.ndim == 1 and key.endswith("weight")):
                out[key] = torch.ones_like(t)
            elif key.endswith(("running_mean", "bias")) or t.ndim == 0:
                out[key] = torch.zeros_like(t)
            else:
                fan_in = int(np.prod(t.shape[1:])) if t.ndim > 1 else int(t.shape[0])
                values = rng.standard_normal(tuple(t.shape)) / np.sqrt(max(fan_in, 1))
                out[key] = torch.from_numpy(values.astype(np.float32))
        return out

    kwargs = model_kwargs_from_result(
        {"backbone": "mobilenet_v2", "feature": "logmel", "boundary_head": True}
    )
    return {
        "format": BUNDLE_FORMAT,
        "model_kwargs": kwargs,
        "model": fill(AttentionFusionModel(**kwargs).state_dict()),
        "backbone_name": "mobilenet_v2",
        "backbone": fill(build_backbone("mobilenet_v2", pretrained=False).state_dict()),
        "postprocess": dict(REGRESSION_POSTPROCESS),
        "source": {"synthetic": True, "numpy_seed": SEED},
    }


def make_tiny_videos(out_dir: Path = FIXTURES) -> tuple[Path, Path]:
    """Write `tiny_real.mkv` and `tiny_fake.mkv` (2 s, 25 fps, 96x96, 16 kHz mono PCM).

    `tiny_fake` swaps both modalities over `FAKE_SPAN`: a different test pattern and a
    different tone, so it is "partially fake" in the same shape as a LAV-DF clip. The
    generated bytes depend on the ffmpeg build, which is why the files are committed rather
    than regenerated per run.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    s0, s1 = FAKE_SPAN
    common = ["ffmpeg", "-v", "error", "-y", "-bitexact"]
    enc = [
        "-c:v", "libx264", "-preset", "veryslow", "-crf", "30", "-pix_fmt", "yuv420p",
        "-g", "25", "-bf", "0", "-flags", "+bitexact",
        "-c:a", "pcm_s16le", "-ar", "16000", "-ac", "1",
    ]  # fmt: skip
    real = out_dir / TINY_REAL.name
    subprocess.run(
        [
            *common,
            "-f", "lavfi", "-i", f"testsrc2=size=96x96:rate=25:duration={SECONDS}",
            "-f", "lavfi", "-i", f"sine=frequency=440:sample_rate=16000:duration={SECONDS}",
            *enc, "-shortest", str(real),
        ],
        check=True,
    )  # fmt: skip
    fake = out_dir / TINY_FAKE.name
    video = (
        f"testsrc2=size=96x96:rate=25:duration={SECONDS}[a];"
        f"smptebars=size=96x96:rate=25:duration={SECONDS}[b];"
        f"[a][b]overlay=enable='between(t,{s0},{s1 - 0.001})'[v]"
    )
    audio = (
        f"sine=frequency=440:sample_rate=16000:duration={SECONDS}[x];"
        f"sine=frequency=880:sample_rate=16000:duration={SECONDS}[y];"
        f"[x]volume=enable='between(t,{s0},{s1})':volume=0[x0];"
        f"[y]volume=enable='not(between(t,{s0},{s1}))':volume=0[y0];"
        f"[x0][y0]amix=inputs=2:normalize=0[aout]"
    )
    subprocess.run(
        [
            *common,
            "-filter_complex", f"{video};{audio}",
            "-map", "[v]", "-map", "[aout]",
            *enc, "-t", str(SECONDS), str(fake),
        ],
        check=True,
    )  # fmt: skip
    return real, fake


# Report detail from `analyze(details=True)` -- pinned too, so the PDF's evidence cannot drift.
DETAIL_ARRAYS = ("audio_only_scores", "visual_only_scores", "attention")


def result_summary(res) -> dict:
    """The parts of an `AnalysisResult` the regression pins, in JSON-ready form."""
    out = {
        "n_frames": res.n_frames,
        "clip_score": float(res.clip_score),
        "frame_scores": [float(x) for x in res.frame_scores],
        "segments": [[float(s), float(e), float(c)] for s, e, c in res.segments],
        "face_found_fraction": float(res.face_found_fraction),
        "audio_silent": bool(res.audio_silent),
    }
    for key in DETAIL_ARRAYS:
        arr = getattr(res, key, None)
        if arr is not None:
            out[key] = [float(x) for x in arr]
    if getattr(res, "boundary_scores", None) is not None:
        out["boundary_scores"] = [[float(a), float(b)] for a, b in res.boundary_scores]
    for key in ("audio_only_clip", "visual_only_clip"):
        if getattr(res, key, None) is not None:
            out[key] = float(getattr(res, key))
    if getattr(res, "keyframes", None):
        out["keyframes"] = [[k.frame, k.role, k.segment] for k in res.keyframes]
    return out
